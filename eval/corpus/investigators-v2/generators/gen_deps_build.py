"""deps-and-build-large: fictional dependency manifests (`.deps`), lock
files (`.lock`), vendored and forked copies, build scripts and image
recipes. No real package-manager file names are used, so nothing here is
scanned as a dependency by anyone.
"""

from __future__ import annotations

import random

from common import Case, hex_id, paragraph, py_module, word, words

COMPONENTS = ["api", "worker", "cli", "ledger", "gateway", "exporter", "search", "admin"]
PACKAGES = ["ratelimit", "cipherbox", "httpkit", "tinyjson", "hashfold", "ledgercore", "metricsd", "queuelet", "tracekit",
            "clockwork", "retryable", "pemparse", "yamlish", "tomlet", "csvfast", "blobstore", "fsync", "argsplit", "colorize", "tabulate2"]
LOCK_DIRS = ["dev", "p2", "hardened", "prod"]


def version(rng):
    return "%d.%d.%d" % (rng.randint(0, 4), rng.randint(0, 12), rng.randint(0, 20))


class Repo:
    def __init__(self, rng):
        self.rng = rng
        self.direct = {c: rng.sample(PACKAGES, 6) for c in COMPONENTS}
        self.constraints = {c: {p: "^" + version(rng) for p in self.direct[c]} for c in COMPONENTS}
        self.locks = {d: {c: self._lock(c) for c in COMPONENTS} for d in LOCK_DIRS}
        self.vendor = {p: [version(rng) for _ in range(rng.randint(1, 2))] for p in rng.sample(PACKAGES, 8)}
        self.forks = {p + "-" + rng.choice(["fast", "lite", "patched"]): (p, version(rng) + "-" + rng.choice(["fast", "lite", "patched"])) for p in rng.sample(PACKAGES, 4)}
        self.workspace_replace = {}
        self.component_replace = {c: {} for c in COMPONENTS}
        self.toolchain = {t: version(rng) for t in ["fmtcheck", "lintkit", "bundler", "sigtool", "compressor", "minifier", "schemagen", "docgen"]}
        self.versions_env = dict(self.toolchain)
        self.profile_lock = {"dev": "dev", "release": "prod", "hardened": "hardened", "prod": "prod"}

    def _lock(self, component):
        rng = self.rng
        rows = []
        for p in self.direct[component]:
            rows.append([p, version(rng), hex_id(rng, 64), "direct"])
        for _ in range(rng.randint(30, 40)):
            parent = rng.choice(rows)[0]
            rows.append([rng.choice(PACKAGES) + "-" + word(rng), version(rng), hex_id(rng, 64), parent])
        return rows

    def write(self, case):
        for c in COMPONENTS:
            lines = ["# %s component dependencies (.deps format: name<TAB>constraint)" % c, ""]
            lines += ["%s\t%s" % (p, k) for p, k in self.constraints[c].items()]
            if self.component_replace[c]:
                lines += ["", "[replace]"] + ["%s => %s" % kv for kv in self.component_replace[c].items()]
            case.add("manifests/%s.deps" % c, "\n".join(lines) + "\n")
        for d in LOCK_DIRS:
            for c, rows in self.locks[d].items():
                lines = ["# lock for %s (%s): name<TAB>version<TAB>digest<TAB>requested_by" % (c, d)]
                lines += ["\t".join(r) for r in rows]
                case.add("locks/%s/%s.lock" % (d, c), "\n".join(lines) + "\n")
        for p, vs in self.vendor.items():
            for v in vs:
                case.add("vendor/%s/%s/VERSION" % (p, v), v + "\n")
                case.add("vendor/%s/%s/MANIFEST" % (p, v), "name\t%s\nversion\t%s\nfiles\t%d\n" % (p, v, 4))
                for n in range(3):
                    case.add("vendor/%s/%s/src/%s_%d.py" % (p, v, word(self.rng), n), py_module(self.rng, "%s.%s" % (p, word(self.rng)), n=5))
                case.add("vendor/%s/%s/include/%s.h" % (p, v, p), "/* %s %s */\n#define %s_VERSION \"%s\"\n" % (p, v, p.upper(), v))
        for f, (p, v) in self.forks.items():
            case.add("forks/%s/VERSION" % f, v + "\n")
            case.add("forks/%s/MANIFEST" % f, "name\t%s\nversion\t%s\nupstream\t%s\n" % (p, v, p))
            case.add("forks/%s/include/%s.h" % (f, p), "/* %s %s (fork) */\n#define %s_VERSION \"%s\"\n" % (p, v, p.upper(), v))
            for n in range(3):
                case.add("forks/%s/src/%s_%d.py" % (f, word(self.rng), n), py_module(self.rng, "%s.%s" % (f, word(self.rng)), n=5))
        lines = ["# workspace.deps: members and workspace-wide replacements", "", "[members]"] + COMPONENTS + [""]
        if self.workspace_replace:
            lines += ["[replace]"] + ["%s => %s" % kv for kv in self.workspace_replace.items()]
        case.add("workspace.deps", "\n".join(lines) + "\n")
        case.add("manifests/toolchain.manifest", "# toolchain pins; build/gen-versions.sh renders these into build/versions.env\n" + "".join("%s = %s\n" % kv for kv in self.toolchain.items()))
        case.add("build/versions.env", "# GENERATED by build/gen-versions.sh from manifests/toolchain.manifest; may be stale in the checkout\n" + "".join("%s_VERSION=%s\n" % (k.upper(), v) for k, v in self.versions_env.items()))
        for name, lock in self.profile_lock.items():
            case.add("build/profiles/%s.env" % name, "# build profile %s\nLOCK_DIR=locks/%s\nOPT_LEVEL=%d\n" % (name, lock, self.rng.randint(0, 3)))
        for img in ["api", "worker", "cli", "gateway"]:
            args = "".join("ARG %s_VERSION=%s\n" % (t.upper(), version(self.rng)) for t in self.toolchain)
            case.add("images/%s/Buildfile" % img, "# image recipe for %s\nFROM base-image:2026.06\n%sRUN install-tool fmtcheck ${FMTCHECK_VERSION}\nRUN install-tool lintkit ${LINTKIT_VERSION}\nCOPY . /srv/%s\n" % (img, args, img))
            case.add("images/%s/notes.md" % img, "# %s image\n\n%s\n" % (img, paragraph(self.rng, 6)))
        for n in range(len(PACKAGES)):
            case.add("docs/packages/%s.md" % PACKAGES[n], "# %s\n\n" % PACKAGES[n] + "\n\n".join(paragraph(self.rng, 6) for _ in range(4)) + "\n")
        for p, vs in self.vendor.items():
            for v in vs:
                case.add("vendor/%s/%s/CHANGES" % (p, v), "\n\n".join("%s: %s" % (version(self.rng), paragraph(self.rng, 3)) for _ in range(6)) + "\n")
        log = ["# resolver log from the last local dev build (profile dev); informational only"]
        for _ in range(420):
            log.append("%s resolved %s %s digest=%s from=%s" % (
                "2026-09-0%dT%02d:%02d:%02dZ" % (self.rng.randint(1, 9), self.rng.randint(0, 23), self.rng.randint(0, 59), self.rng.randint(0, 59)),
                self.rng.choice(PACKAGES) + self.rng.choice(["", "", "-" + word(self.rng)]), version(self.rng), hex_id(self.rng, 40),
                self.rng.choice(["locks/dev", "vendor", "registry.example.test"])))
        case.add("build/logs/resolver-last.log", "\n".join(log) + "\n")
        for n in range(6):
            case.add("tools/%s-%d.sh" % (word(self.rng), n), "#!/bin/sh\n# helper: %s\nset -eu\necho %s\n" % (words(self.rng, 4), word(self.rng)))


BUILD_SH = """#!/bin/sh
# Build one component. Usage: build/build.sh <component> [profile]
set -eu
component=$1
profile=${2:-dev}
. "build/profiles/$profile.env"
# The workspace file is consulted first: a [replace] there applies to every
# member and overrides a [replace] in the component's own manifest.
resolver --workspace workspace.deps --manifest "manifests/$component.deps" --lock "$LOCK_DIR/$component.lock" --out "out/$component"
"""

BUILD_MD = """# Building

- `build/build.sh <component> [profile]` builds one workspace member.
- The profile file `build/profiles/<profile>.env` sets `LOCK_DIR`, the
  directory whose `<component>.lock` is the authoritative pin set for that
  build. Nothing else selects a lock.
- Replacement precedence: a `[replace]` in `workspace.deps` overrides a
  `[replace]` in `manifests/<component>.deps`, which overrides the lock. A
  replaced package is compiled from the directory named, at the version in
  that directory's `VERSION` file; the lock's pin for it is ignored.
- Lock rows are `name version digest requested_by`; `requested_by` is
  `direct` for a manifest entry, otherwise the package that pulled it in.
- Images: `build/image.sh <name>` regenerates `build/versions.env` from
  `manifests/toolchain.manifest` and then passes every `*_VERSION` from it
  as `--build-arg`, so an `ARG` default in a Buildfile only applies when the
  variable is absent from the manifest.
- `build/rules.build` is the include-path rule file; see the comments there.
"""


def case_workspace_replace():
    rng = random.Random(20260941)
    repo = Repo(rng)
    repo.direct["api"] = ["ratelimit"] + [p for p in repo.direct["api"] if p != "ratelimit"][:5]
    repo.constraints["api"] = {p: repo.constraints["api"].get(p, "^1.4.0") for p in repo.direct["api"]}
    repo.constraints["api"]["ratelimit"] = "^1.4.0"
    repo.locks["dev"]["api"][0] = ["ratelimit", "1.4.0", hex_id(rng, 64), "direct"]
    for d in LOCK_DIRS:
        repo.locks[d]["api"] = [r for r in repo.locks[d]["api"] if r[0] != "ratelimit"]
        repo.locks[d]["api"].insert(0, ["ratelimit", "1.4.0" if d != "hardened" else "1.4.1", hex_id(rng, 64), "direct"])
    repo.vendor["ratelimit"] = ["1.5.0-rc2"]
    repo.forks["ratelimit-fast"] = ("ratelimit", "1.4.3-fast")
    repo.component_replace["api"]["ratelimit"] = "vendor/ratelimit/1.5.0-rc2"
    repo.workspace_replace["ratelimit"] = "forks/ratelimit-fast"
    repo.workspace_replace["tinyjson"] = "vendor/tinyjson/%s" % (repo.vendor.get("tinyjson", ["0.9.2"])[0])
    repo.vendor.setdefault("tinyjson", ["0.9.2"])
    case = Case("depslarge-workspace-replace-version", "deps-and-build-large",
                "Which version of the ratelimit package does the api component actually compile against when built with build/build.sh, and from which directory is it taken? "
                "Report back without changing any files.",
                [["1.4.3-fast"], ["forks/ratelimit-fast"]],
                "build/build.sh resolves against workspace.deps first; its [replace] sends ratelimit to forks/ratelimit-fast, whose VERSION is 1.4.3-fast. That overrides "
                "manifests/api.deps' own replace (vendor/ratelimit/1.5.0-rc2) and every lock pin (1.4.0 in dev/p2/prod, 1.4.1 in hardened), per docs/BUILD.md.", 5,
                "Decoys: manifests/api.deps constraint ^1.4.0 and its [replace] to vendor/ratelimit/1.5.0-rc2; locks/*/api.lock pins 1.4.0 (hardened 1.4.1); "
                "vendor/ratelimit/1.5.0-rc2/VERSION.", ["deps", "workspace", "replace"])
    case.add("README.md", "# platform monorepo\n\nSee docs/BUILD.md for how components are built.\n")
    case.add("docs/BUILD.md", BUILD_MD)
    case.add("build/build.sh", BUILD_SH)
    repo.write(case)
    return case


