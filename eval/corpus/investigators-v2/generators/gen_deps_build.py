def case_image_tool_version():
    rng = random.Random(20260943)
    repo = Repo(rng)
    repo.toolchain["fmtcheck"] = "2.3.1"
    repo.versions_env = dict(repo.toolchain)
    repo.versions_env["fmtcheck"] = "2.2.0"
    case = Case("depslarge-image-tool-version", "deps-and-build-large",
                "Which version of the fmtcheck tool ends up installed in the image that build/image.sh builds from images/api/Buildfile? Report back without changing any files.",
                [["2.3.1"]],
                "image.sh runs build/gen-versions.sh first, which rewrites build/versions.env from manifests/toolchain.manifest (fmtcheck = 2.3.1), then passes "
                "FMTCHECK_VERSION=2.3.1 as --build-arg. The checked-in versions.env (2.2.0) is stale, the Buildfile's ARG default only applies when the variable is absent, and "
                "images/worker/Buildfile is a different image.", 5,
                "Decoys: the ARG FMTCHECK_VERSION default in images/api/Buildfile; the stale build/versions.env (2.2.0); other images' ARG defaults; docs/images.md.",
                ["deps", "images", "build-args"])
    case.add("README.md", "# platform monorepo\n\nSee docs/BUILD.md for how components and images are built.\n")
    case.add("docs/BUILD.md", BUILD_MD)
    case.add("docs/images.md", "# Images\n\nfmtcheck 2.2.0 is installed in every image (see build/versions.env).\n\n" + paragraph(rng, 8) + "\n")
    case.add("build/build.sh", BUILD_SH)
    case.add("build/image.sh", """#!/bin/sh
# Build one image. Usage: build/image.sh <name>
set -eu
name=$1
sh build/gen-versions.sh
args=""
while IFS='=' read -r key value; do
  case "$key" in ''|'#'*) continue ;; esac
  args="$args --build-arg $key=$value"
done < build/versions.env
image-build $args -f "images/$name/Buildfile" -t "$name:latest" .
""")
    case.add("build/gen-versions.sh", """#!/bin/sh
# Render manifests/toolchain.manifest into build/versions.env (KEY_VERSION=value).
set -eu
{
  echo "# GENERATED by build/gen-versions.sh from manifests/toolchain.manifest; may be stale in the checkout"
  sed -n 's/^\\([a-z]*\\) *= *\\(.*\\)$/\\U\\1\\E_VERSION=\\2/p' manifests/toolchain.manifest
} > build/versions.env
""")
    repo.write(case)
    import re
    case.files["images/api/Buildfile"] = re.sub(r"ARG FMTCHECK_VERSION=[^\n]*", "ARG FMTCHECK_VERSION=2.0.0", case.files["images/api/Buildfile"], count=1)
    return case


def case_transitive_source():
    rng = random.Random(20260944)
    repo = Repo(rng)
    repo.direct["ledger"] = ["ledgercore", "metricsd", "clockwork", "pemparse", "csvfast", "argsplit"]
    repo.constraints["ledger"] = {p: "^" + version(rng) for p in repo.direct["ledger"]}
    repo.profile_lock["prod"] = "p2"
    repo.profile_lock["release"] = "p2"
    for d in LOCK_DIRS:
        rows = [r for r in repo.locks[d]["ledger"] if r[0] not in ("tinyjson", "httpkit", "ledgercore", "metricsd")]
        rows.insert(0, ["ledgercore", "2.4.0", hex_id(rng, 64), "direct"])
        rows.insert(1, ["metricsd", "0.8.1", hex_id(rng, 64), "direct"])
        if d == "p2":
            rows.insert(2, ["httpkit", "1.9.2", hex_id(rng, 64), "ledgercore"])
            rows.insert(3, ["tinyjson", "0.9.4", hex_id(rng, 64), "httpkit"])
        else:
            rows.insert(2, ["tinyjson", "1.0.0", hex_id(rng, 64), "metricsd"])
        repo.locks[d]["ledger"] = rows
    repo.vendor["tinyjson"] = ["0.9.2"]
    case = Case("depslarge-transitive-source", "deps-and-build-large",
                "For the ledger component built with the prod profile, which direct dependency (from manifests/ledger.deps) is responsible for pulling in tinyjson, and which "
                "tinyjson version does that build's lock resolve? Report back without changing any files.",
                [["ledgercore"], ["0.9.4"]],
                "build/profiles/prod.env sets LOCK_DIR=locks/p2, so the authoritative lock is locks/p2/ledger.lock. There tinyjson 0.9.4 is requested_by httpkit, httpkit is "
                "requested_by ledgercore, and ledgercore is direct (listed in manifests/ledger.deps). locks/prod, dev and hardened show tinyjson 1.0.0 via metricsd, and "
                "vendor/tinyjson is 0.9.2 but nothing replaces to it.", 5,
                "Decoys: locks/prod/ledger.lock (tinyjson 1.0.0 requested_by metricsd), which the prod profile does not use; locks/dev and locks/hardened (same); "
                "vendor/tinyjson/0.9.2; metricsd as the apparent parent.", ["deps", "locks", "transitive"])
    case.add("README.md", "# platform monorepo\n\nSee docs/BUILD.md for how components are built.\n")
    case.add("docs/BUILD.md", BUILD_MD)
    case.add("build/build.sh", BUILD_SH)
    repo.write(case)
    return case


def case_include_path():
    rng = random.Random(20260945)
    repo = Repo(rng)
    repo.vendor["hashfold"] = ["2.1.0", "2.0.5"]
    repo.forks["hashfold-lite"] = ("hashfold", "2.1.0-lite")
    case = Case("depslarge-include-path-vendor", "deps-and-build-large",
                "Which directory's copy of the hashfold headers does the cli target compile against under build/rules.build, once every included rule file is applied? "
                "Give the include directory path. Report back without changing any files.",
                [["forks/hashfold-lite/include"]],
                "rules.build sets HASHFOLD_INC to vendor/hashfold/2.1.0/include via build/paths.mk, but it includes build/overrides.mk afterwards, which redefines "
                "HASHFOLD_INC = forks/hashfold-lite/include; the rule file's comment says the last definition wins and the cli target's INCLUDE uses HASHFOLD_INC. "
                "vendor/hashfold/2.0.5 is referenced only by the legacy target and third_party/hashfold by nothing.", 5,
                "Decoys: vendor/hashfold/2.1.0/include (paths.mk); vendor/hashfold/2.0.5/include (legacy target); third_party/hashfold/include (unreferenced); "
                "docs/BUILD.md does not mention overrides.mk.", ["deps", "build-rules", "include-path"])
    case.add("README.md", "# platform monorepo\n\nSee docs/BUILD.md for how components are built.\n")
    case.add("docs/BUILD.md", BUILD_MD)
    case.add("build/build.sh", BUILD_SH)
    case.add("build/rules.build", """# rules.build: include-path rules. A variable may be assigned several times;
# the LAST assignment in include order wins, exactly like the rule engine.
include build/paths.mk
include build/targets.mk
include build/overrides.mk

[target cli]
INCLUDE = $(HASHFOLD_INC) $(COMMON_INC)
SOURCES = cli/*.py

[target legacy]
INCLUDE = vendor/hashfold/2.0.5/include $(COMMON_INC)
SOURCES = legacy/*.py
""")
    case.add("build/paths.mk", "COMMON_INC = include\nHASHFOLD_INC = vendor/hashfold/2.1.0/include\nCIPHERBOX_INC = vendor/cipherbox/3.0.4/include\n")
    case.add("build/targets.mk", "# per-target tuning\nOPT_cli = 2\nOPT_legacy = 0\n")
    case.add("build/overrides.mk", "# local overrides applied last\nHASHFOLD_INC = forks/hashfold-lite/include\n")
    case.add("third_party/hashfold/include/hashfold.h", "/* unreferenced copy */\n#define HASHFOLD_VERSION \"1.9.0\"\n")
    case.add("third_party/hashfold/README", "Kept for the archived importer; no rule references this directory.\n")
    repo.write(case)
    return case


def cases():
    return [case_workspace_replace(), case_lock_profile_pin(), case_image_tool_version(), case_transitive_source(), case_include_path()]
